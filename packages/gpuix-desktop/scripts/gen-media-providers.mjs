// Regenerate the static media-provider list from the gateway's own registry.
//
// The staged standalone runtime exposes no provider-catalog endpoint, so the
// native shell ships a generated snapshot instead of guessing. tests/media-
// providers.test.mjs fails when the snapshot drifts from the registry.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..", "..");
const registryPath = path.join(repoRoot, "open-sse", "providers", "registry", "index.js");
const registry = (await import(pathToFileURL(registryPath).href)).default;

const entries = registry
  .filter((entry) => !entry.hidden)
  .map((entry) => {
    const kinds = entry.serviceKinds ?? ["llm"];
    if (!kinds.some((kind) => kind !== "llm")) return null;
    const row = {
      id: entry.id,
      name: (entry.display && entry.display.name) || entry.id,
      kinds,
      noAuth: entry.noAuth === true,
      priority: entry.priority ?? entry.mediaPriority ?? 999,
    };
    if (entry.hiddenKinds) row.hiddenKinds = entry.hiddenKinds;
    return row;
  })
  .filter(Boolean)
  .sort((a, b) => a.priority - b.priority || a.id.localeCompare(b.id));

const body = `// Generated by scripts/gen-media-providers.mjs — do not edit by hand.
// Source: open-sse/providers/registry/index.js (media-capable, non-hidden entries).
export const MEDIA_PROVIDERS = ${JSON.stringify(entries, null, 2)};
`;

const target = path.resolve(here, "..", "src", "ui", "media-providers.generated.mjs");
fs.writeFileSync(target, body);
console.log(`[gen] ${entries.length} media providers → ${path.relative(repoRoot, target)}`);
